import { dirname } from "node:path";

export function graphicSandboxArgs(
  runtime: string,
  directory: string,
): string[] {
  const system = [
    "/usr",
    "/bin",
    "/sbin",
    "/lib",
    "/lib64",
    "/etc/fonts",
    "/etc/ld.so.cache",
    "/etc/localtime",
  ];
  return [
    ...system.flatMap((path) => ["--ro-bind-try", path, path]),
    "--tmpfs",
    "/tmp",
    "--dev",
    "/dev",
    "--proc",
    "/proc",
    "--dir",
    "/tmp/home",
    "--dir",
    "/tmp/cache",
    "--bind",
    directory,
    directory,
    "--ro-bind",
    runtime,
    runtime,
    "--ro-bind",
    dirname(process.execPath),
    dirname(process.execPath),
    "--clearenv",
    "--setenv",
    "PATH",
    "/usr/bin:/bin",
    "--setenv",
    "HOME",
    "/tmp/home",
    "--setenv",
    "XDG_CACHE_HOME",
    "/tmp/cache",
    "--setenv",
    "ELECTRON_RUN_AS_NODE",
    "1",
    "--chdir",
    directory,
    "--unshare-pid",
    "--unshare-net",
    "--unshare-ipc",
    "--unshare-uts",
    "--die-with-parent",
    "--new-session",
  ];
}
