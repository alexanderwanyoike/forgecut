import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { bundle } from '@remotion/bundler';
import { renderMedia, renderStill, selectComposition } from '@remotion/renderer';

const run = (args) => execFileSync('ffmpeg', ['-v', 'error', '-threads', '1', '-filter_threads', '1', ...args.slice(0, -1), '-threads', '1', args.at(-1)], { maxBuffer: 10 * 1024 * 1024 });
const serveUrl = await bundle({ entryPoint: resolve('src/render-entry.tsx'), publicDir: resolve('public'), outDir: resolve('results/remotion-bundle') });
const common = { serveUrl, browserExecutable: process.env.FORGECUT_CHECK_BROWSER ?? '/usr/bin/google-chrome', chromiumOptions: { gl: 'swangle' }, inputProps: { title: 'Your build', accent: '#70a08b' }, logLevel: 'error' };
const composition = await selectComposition({ ...common, id: 'CheckGraphic' });
await renderStill({ ...common, composition, frame: 15, imageFormat: 'png', output: resolve('results/graphic.png') });
await renderMedia({ ...common, composition, codec: 'prores', proResProfile: '4444', pixelFormat: 'yuva444p10le', imageFormat: 'png', concurrency: 1, outputLocation: resolve('results/graphic.mov') });
run(['-f', 'lavfi', '-i', 'color=c=0x24292c:s=640x360:r=30:d=1', '-an', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-y', 'results/source.mkv']);
run(['-i', 'results/source.mkv', '-i', 'results/graphic.mov', '-filter_complex_threads', '1', '-filter_complex', '[0:v][1:v]overlay=0:0:format=auto,format=yuv420p[v]', '-map', '[v]', '-an', '-c:v', 'libx264', '-y', 'results/composite.mp4']);
const probe = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_streams', '-show_format', '-of', 'json', 'results/composite.mp4'], { encoding: 'utf8' }));
const video = probe.streams.find((stream) => stream.codec_type === 'video');
assert.equal(Number(video.nb_frames), 30);
assert.equal(video.width, 640);
assert.equal(video.height, 360);
assert.equal(Number(probe.format.duration), 1);
const rgba = run(['-i', 'results/graphic.png', '-frames:v', '1', '-f', 'rawvideo', '-pix_fmt', 'rgba', '-']);
assert.equal(rgba[3], 0, 'Graphic background is not transparent');
const imagePixel = (40 * 640 + 40) * 4;
assert.equal(rgba[imagePixel + 3], 255, 'Image asset missing from graphic');
const decoded = run(['-ss', '0.5', '-i', 'results/composite.mp4', '-frames:v', '1', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-']);
assert(decoded[imagePixel / 4 * 3 + 1] > decoded[imagePixel / 4 * 3], 'Graphic image was not composited over footage');
const report = { transparentStill: true, alphaVideo: true, ffmpegComposite: true, frames: Number(video.nb_frames), durationSeconds: Number(probe.format.duration), concurrency: 1, browserExecutable: common.browserExecutable };
await writeFile('results/render.json', `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify(report));
